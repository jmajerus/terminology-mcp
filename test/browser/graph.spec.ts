test('tree graph connections preview parent replacement, descendant aliases and set effects; stale and cyclic changes do not apply',async({page,request})=>{
 const scheme='connect-tree';await request.post('/api/schemes',{data:{id:scheme,label:'Tree connections',hierarchy:'tree'}});
 const add=async(label:string,broader:string[]=[]) => (await(await request.post('/api/terms',{data:{scheme,label,broader}})).json()).term;
 const old=await add('Old parent'),parent=await add('Parent'),child=await add('Child',[old.id]),descendant=await add('Descendant',[child.id]);
 let version=(await(await request.get('/api/state')).json()).version;
 await request.post('/api/sets',{data:{set:{scheme,slug:'descendants',label:'Parent descendants',recipe:{narrower:[parent.id]}},expectedVersion:version}});
 await page.goto(`/graph?scheme=${scheme}#${child.id}`);await expect(page.locator('#graph-detail h1')).toHaveText('Child');
 await page.locator('#graph-link-type').selectOption('broader');await page.locator('#graph-target').selectOption(descendant.id);
 await page.getByRole('button',{name:'Preview relationship',exact:true}).click();
 await expect(page.locator('#graph-notice')).toContainText('cycle');await expect(page.locator('#graph-hierarchy-dialog')).not.toBeVisible();
 await page.locator('#graph-target').selectOption(parent.id);await page.getByRole('button',{name:'Preview relationship',exact:true}).click();
 const dialog=page.locator('#graph-hierarchy-dialog');await expect(dialog).toContainText('current parent will be replaced');
 await expect(dialog).toContainText('Parent descendants');await expect(dialog).toContainText('0 → 2 terms');
 await add('Concurrent change');await dialog.getByRole('button',{name:'Apply change',exact:true}).click();
 await expect(page.locator('#graph-hierarchy-error')).toContainText('workspace changed');
 expect((await(await request.get(`/api/terms/${child.id}`)).json()).term.broader).toEqual([old.id]);
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
 version=(await(await request.get('/api/state')).json()).version;
 await page.getByRole('button',{name:'Refresh',exact:true}).click();
 await expect(page.locator('#graph-version')).toHaveText('#'+version);
 await expect(page.locator('#graph-notice')).not.toBeVisible();
 await page.locator('#graph-target').selectOption(parent.id);await page.getByRole('button',{name:'Preview relationship',exact:true}).click();
 await dialog.getByRole('button',{name:'Apply change',exact:true}).click();await expect(dialog).not.toBeVisible();
 await expect(page.getByRole('button',{name:'Remove broader Parent',exact:true})).toBeVisible();
 const after=(await(await request.get(`/api/terms/${child.id}`)).json()).term;expect(after.broader).toEqual([parent.id]);
 const grandchild=(await(await request.get(`/api/terms/${descendant.id}`)).json()).term;
 expect(grandchild.path).toBe('parent/child/descendant');expect(grandchild.aliases).toContain('connect-tree:old-parent/child/descendant');
});

test('refresh discards a delayed hierarchy preview',async({page,request})=>{
 const scheme='connect-delayed';await request.post('/api/schemes',{data:{id:scheme,label:scheme,hierarchy:'graph'}});
 const a=(await(await request.post('/api/terms',{data:{scheme,label:'A'}})).json()).term;
 const b=(await(await request.post('/api/terms',{data:{scheme,label:'B'}})).json()).term;
 await page.goto(`/graph?scheme=${scheme}#${a.id}`);await expect(page.locator('#graph-detail h1')).toHaveText('A');
 await page.locator('#graph-link-type').selectOption('broader');await page.locator('#graph-target').selectOption(b.id);
 let release!:()=>void;const pending=new Promise<void>(resolve=>{release=resolve;});
 await page.route('**/operations/preview',async route=>{const response=await route.fetch();await pending;await route.fulfill({response});});
 const started=page.waitForRequest('**/operations/preview');await page.getByRole('button',{name:'Preview relationship',exact:true}).click();await started;
 await page.getByRole('button',{name:'Refresh',exact:true}).click();
 await expect(page.locator('#graph-link-form')).not.toHaveAttribute('inert','');
 const completed=page.waitForResponse('**/operations/preview');release();await completed;
 await expect(page.locator('#graph-hierarchy-dialog')).not.toBeVisible();
 expect((await(await request.get(`/api/terms/${a.id}`)).json()).term.broader).toEqual([]);
});
