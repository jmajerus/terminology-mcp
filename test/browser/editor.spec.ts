test('a stale tab shows a conflict and retains its unsaved text', async ({ page, context, request }) => {
  const scheme = await request.post('/api/schemes', { data: { id: 'conflict', label: 'Conflict test', hierarchy: 'tree' } });
  expect(scheme.ok()).toBe(true);
  const added = await request.post('/api/terms', { data: { scheme: 'conflict', label: 'Original' } });
  const { term } = await added.json();
  const other = await context.newPage();
  await page.goto(`/#${term.id}`);
  await other.goto(`/#${term.id}`);
  await expect(page.locator('#scope-note')).toBeVisible();
  await expect(other.locator('#scope-note')).toBeVisible();
  await page.locator('#scope-note').fill('Saved by the first tab.');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.locator('#save-state')).toHaveText(/Saved at/);
  await other.locator('#scope-note').fill('Unsaved text in the second tab.');
  await other.getByRole('button', { name: 'Save changes' }).click();
  await expect(other.locator('#save-error')).toContainText('changed since');
  await expect(other.locator('#scope-note')).toHaveValue('Unsaved text in the second tab.');
  await other.close();
});

test('SKOS file import, export, and the four structural actions work through previews', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Import SKOS…', exact: true }).click();
  const dialog = page.locator('#import-dialog');
  await page.locator('#import-file').setInputFiles(fileURLToPath(new URL('../fixtures/research.ttl', import.meta.url)));
  await dialog.getByRole('button', { name: 'Find schemes', exact: true }).click();
  await expect(page.locator('#import-source-scheme')).toBeEnabled();
  await page.locator('#import-id').fill('ui-research');
  await dialog.getByRole('button', { name: 'Preview import', exact: true }).click();
  await expect(page.locator('#import-preview')).toContainText('3 terms');
  await expect(page.locator('#import-preview')).toContainText('Review omitted data');
  await dialog.getByRole('button', { name: 'Import scheme', exact: true }).click();
  await expect(page.locator('#scheme')).toHaveValue('ui-research');
  await page.locator('#tree').getByRole('button', { name: 'Child', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Child', exact: true })).toBeVisible();
  await expect(page.getByLabel('Reference match')).toHaveCount(5);
  const data = await (await request.get('/api/state')).json();
  const peer = data.terms.find((term: { scheme: string; label: string }) => term.scheme === 'ui-research' && term.label === 'Peer');
  await page.getByRole('button', { name: 'Move…', exact: true }).click();
  const op = page.locator('#operation-dialog');
  await page.locator('#operation-broader').selectOption(peer.id);
  await op.getByRole('button', { name: 'Preview change', exact: true }).click();
  await expect(page.locator('#operation-preview')).toContainText('root/peer/child');
  // A write after preview invalidates its apply, without losing the dialog.
  const added = await request.post('/api/terms', { data: { scheme: 'ui-research', label: 'Extra' } });
  expect(added.ok()).toBe(true);
  await op.getByRole('button', { name: 'Apply change', exact: true }).click();
  await expect(page.locator('#operation-error')).toContainText('workspace changed');
  await op.getByRole('button', { name: 'Preview change', exact: true }).click();
  await op.getByRole('button', { name: 'Apply change', exact: true }).click();
  await expect(op).not.toBeVisible();
  await expect(page.locator('.alias-list').filter({ hasText: 'ui-research:root/child' })).toContainText('ui-research:root/peer/child');
  await page.locator('#tree').getByRole('button', { name: 'Peer', exact: true }).click();
  await page.getByRole('button', { name: 'Split…', exact: true }).click();
  await op.getByLabel('Replacement 1 label', { exact: true }).fill('Branch one');
  await op.getByLabel('Replacement 2 label', { exact: true }).fill('Branch two');
  await page.locator('.split-child').selectOption('1');
  await op.getByRole('button', { name: 'Preview change', exact: true }).click();
  await expect(page.locator('#operation-preview')).toContainText('Branch two');
  await op.getByRole('button', { name: 'Apply change', exact: true }).click();
  await expect(page.locator('.retirement-banner')).toContainText('This term is retired');
  await expect(page.locator('#label')).toBeDisabled();
  const updated = await (await request.get('/api/state')).json();
  const branchTwo = updated.terms.find((term: { scheme: string; label: string }) => term.scheme === 'ui-research' && term.label === 'Branch two');
  await page.locator('#tree').getByRole('button', { name: 'Branch one', exact: true }).click();
  await page.getByRole('button', { name: 'Merge…', exact: true }).click();
  await page.locator('#operation-target').selectOption(branchTwo.id);
  await op.getByRole('button', { name: 'Preview change', exact: true }).click();
  await op.getByRole('button', { name: 'Apply change', exact: true }).click();
  await expect(page.locator('.retirement-banner')).toContainText('Branch two');
  await page.locator('#tree').getByRole('button', { name: 'Root', exact: true }).click();
  await page.getByRole('button', { name: 'Retire…', exact: true }).click();
  await op.getByRole('button', { name: 'Preview change', exact: true }).click();
  await expect(page.locator('#operation-preview')).toContainText('retired');
  await op.getByRole('button', { name: 'Apply change', exact: true }).click();
  await expect(page.locator('.retirement-banner')).toContainText('No replacement');
  const [download] = await Promise.all([
    page.waitForEvent('download'), page.getByRole('link', { name: 'Export SKOS ↓', exact: true }).click(),
  ]);
  expect(download.suggestedFilename()).toBe('taxonomy.ttl');
  await expect(page.locator('#tree')).toContainText('Branch two');
  expect(errors).toEqual([]);
});
